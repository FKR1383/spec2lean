import { readFile, readdir, writeFile } from "node:fs/promises"
import { resolve } from "node:path"

import { PIPELINE_AGENTS } from "./batch-store.js"
import { REPO_ROOT } from "./repo.js"
import { STAGE_PLANS } from "./stage-plan.js"

const agentsDirectory = resolve(REPO_ROOT, ".opencode/agents")
const agentFiles = (await readdir(agentsDirectory))
  .filter((name) => name.endsWith(".md"))
  .sort((left, right) => left.localeCompare(right))

const rows = Object.entries(STAGE_PLANS).map(([stage, plan]) =>
  `| ${stage} | ${plan.agent} | ${plan.successStage} | ${plan.revisionStages.join(", ") || "none"} |`
)

const stageTasks = Object.entries(STAGE_PLANS).flatMap(([stage, plan]) => [
  `### ${stage}`,
  "",
  `Agent: \`${plan.agent}\``,
  "",
  "````text",
  plan.task,
  "````",
  "",
])

const rolePrompts: string[] = []
for (const file of agentFiles) {
  rolePrompts.push(
    `## ${file.replace(/\.md$/, "")}`,
    "",
    `Source of truth: \`.opencode/agents/${file}\``,
    "",
    "````markdown",
    (await readFile(resolve(agentsDirectory, file), "utf8")).trimEnd(),
    "````",
    "",
  )
}

const body = [
  "# Spec2Lean sub-agent prompts",
  "",
  "> Generated by `npm --prefix engine/orchestrator run prompt-readme`. Do not edit this file by hand.",
  "",
  "This document exposes the complete checked-in OpenCode role prompts and the",
  "exact static stage tasks used by the orchestrator. It exists so a human can",
  "review the actual agent contracts without reconstructing them from code.",
  "",
  "## How the final prompt is composed",
  "",
  "Each OpenCode call receives two layers:",
  "",
  "1. the complete role prompt copied below from `.opencode/agents/<agent>.md`;",
  "2. a deterministic runtime prompt assembled in `engine/orchestrator/src/runner.ts`.",
  "",
  "The runtime layer supplies run/language/version/unit identity, exact output",
  "path, stage/attempt, legal next stages, retry/repair diagnostic, exact input",
  "artifact paths and SHA-256 hashes, gate authority (`HUMAN_APPROVED` versus",
  "`BENCHMARK_AUTO_ADVANCED_NOT_HUMAN_APPROVED`), shared-environment scope, and",
  "for Lean/proof work the complete provenance-ID allowlist. It also requires",
  "the final `SPEC2LEAN_RESULT` JSON line and a passing same-session",
  "`candidate_validate` call. Dynamic values are intentionally not duplicated",
  "in this README because the persisted `run.json` and hash-pinned artifacts are",
  "their source of truth.",
  "Before unit work, ingestion hash-verifies every required official source",
  "artifact and builds source-index v2 across HTML/PDF renditions. Source",
  "curation preserves exact quotations and locators; traceability v4 requires",
  "each semantic SOURCE_FACT to reach every required official rendition. The",
  "GUI consumes that manifest and never re-infers evidence from Lean text.",
  "",
  "Architecture generation has an additional deterministic hot-path contract:",
  "one compact indexed retrieval, no browsing of other unit artifacts, a",
  "dedicated schema-bounded architecture writer with a 32-KiB/400-line",
  "artifact ceiling, same-session validation, and at most one",
  "bounded validator repair. Two consecutive model output-length failures stop",
  "that unit instead of consuming the generic retry budget unchanged.",
  "The architect and architecture critic receive one canonical classification",
  "policy: architecture SOURCE_FACTs are internal roots with official locators",
  "in prose; project model boundaries remain DESIGN_DEPENDENCY/ASSUMPTION;",
  "mere silence about an inapplicable hidden feature does not manufacture an",
  "OPEN_QUESTION; and a bounded model boundary may depend on, but never claim",
  "to resolve, a concrete source-level open question.",
  "At Gate A the critic must disposition every state-affecting open question",
  "in SPEC2LEAN_GATE_A_OQ_TRIAGE. Speculative/out-of-scope questions route back",
  "to architecture. Genuine questions remain human boundaries in normal runs.",
  "In explicit auto-approve benchmarks, they receive an immutable non-human",
  "CONSERVATIVE_BOUNDED_SCOPE waiver: the question stays open, disputed cases",
  "must remain partial or precondition-excluded, generated Lean is",
  "BOUNDED_PARTIAL, and neither human approval nor promotion is implied.",
  "",
  "Proof generation has an additional bounded-batch runtime contract containing",
  "up to eight exact frozen theorem headers and current Lean diagnostics.",
  "Parser-equivalent Lean operator spellings are canonicalized, but binder/",
  "hypothesis/conclusion changes remain forbidden. Productive partial proof",
  "batches are telemetry continuations rather than failed retries.",
  "The theorem contract uses schema v2 and requires genuine",
  "OPERATION_FIDELITY and EXECUTION_CORRESPONDENCE obligations with exact",
  "semantic IDs. Proofs establish implementation of approved semantics; they",
  "do not independently prove the official source prose. Every JSON",
  "candidate is duplicate-key checked, and every nonzero critic count requires",
  "the same number of explicit Severity-tagged finding entries. Source",
  "acquisition has a separate publisher/version/URL-scope runtime envelope built",
  "by `source-bootstrap.ts`; its complete role prompt is included below.",
  "",
  "## Executable pipeline roles",
  "",
  PIPELINE_AGENTS.map((agent) => `- \`${agent}\``).join("\n"),
  "",
  "## Stage routing",
  "",
  "| Stage | Agent | Success stage | Legal revision stages |",
  "|---|---|---|---|",
  ...rows,
  "",
  "## Exact static stage tasks",
  "",
  ...stageTasks,
  "# Complete role prompt files",
  "",
  ...rolePrompts,
].join("\n")

await writeFile(resolve(REPO_ROOT, "SUBAGENT_PROMPTS.md"), `${body.trimEnd()}\n`, "utf8")
console.log(JSON.stringify({
  ok: true,
  path: "SUBAGENT_PROMPTS.md",
  agents: agentFiles.length,
  executablePipelineAgents: PIPELINE_AGENTS.length,
  stages: Object.keys(STAGE_PLANS).length,
}, null, 2))
