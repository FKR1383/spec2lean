import { readFile, readdir, writeFile } from "node:fs/promises"
import { resolve } from "node:path"

import { PIPELINE_AGENTS } from "./batch-store.js"
import { REPO_ROOT } from "./repo.js"
import { STAGE_PLANS } from "./stage-plan.js"

const agentsDirectory = resolve(REPO_ROOT, ".opencode/agents")
const agentFiles = (await readdir(agentsDirectory))
  .filter((name) => name.endsWith(".md"))
  .sort((left, right) => left.localeCompare(right))

const rows = Object.entries(STAGE_PLANS).map(([stage, plan]) =>
  `| ${stage} | ${plan.agent} | ${plan.successStage} | ${plan.revisionStages.join(", ") || "none"} |`
)

const stageTasks = Object.entries(STAGE_PLANS).flatMap(([stage, plan]) => [
  `### ${stage}`,
  "",
  `Agent: \`${plan.agent}\``,
  "",
  "````text",
  plan.task,
  "````",
  "",
])

const rolePrompts: string[] = []
for (const file of agentFiles) {
  rolePrompts.push(
    `## ${file.replace(/\.md$/, "")}`,
    "",
    `Source of truth: \`.opencode/agents/${file}\``,
    "",
    "````markdown",
    (await readFile(resolve(agentsDirectory, file), "utf8")).trimEnd(),
    "````",
    "",
  )
}

const body = [
  "# Spec2Lean sub-agent prompts",
  "",
  "> Generated by `npm --prefix engine/orchestrator run prompt-readme`. Do not edit this file by hand.",
  "",
  "This document exposes the complete checked-in OpenCode role prompts and the",
  "exact static stage tasks used by the orchestrator. It exists so a human can",
  "review the actual agent contracts without reconstructing them from code.",
  "",
  "## How the final prompt is composed",
  "",
  "Each OpenCode call receives two layers:",
  "",
  "1. the complete role prompt copied below from `.opencode/agents/<agent>.md`;",
  "2. a deterministic runtime prompt assembled in `engine/orchestrator/src/runner.ts`.",
  "",
  "The runtime layer supplies run/language/version/unit identity, exact output",
  "path, stage/attempt, legal next stages, retry/repair diagnostic, exact input",
  "artifact paths and SHA-256 hashes, gate authority (`HUMAN_APPROVED` versus",
  "`BENCHMARK_AUTO_ADVANCED_NOT_HUMAN_APPROVED`), shared-environment scope, and",
  "for Lean/proof work the complete provenance-ID allowlist. It also requires",
  "the final `SPEC2LEAN_RESULT` JSON line and a passing same-session",
  "`candidate_validate` call. Dynamic values are intentionally not duplicated",
  "in this README because the persisted `run.json` and hash-pinned artifacts are",
  "their source of truth.",
  "",
  "Proof generation has an additional bounded-batch runtime contract containing",
  "the exact frozen theorem headers and current Lean diagnostics. Source",
  "acquisition has a separate publisher/version/URL-scope runtime envelope built",
  "by `source-bootstrap.ts`; its complete role prompt is included below.",
  "",
  "## Executable pipeline roles",
  "",
  PIPELINE_AGENTS.map((agent) => `- \`${agent}\``).join("\n"),
  "",
  "## Stage routing",
  "",
  "| Stage | Agent | Success stage | Legal revision stages |",
  "|---|---|---|---|",
  ...rows,
  "",
  "## Exact static stage tasks",
  "",
  ...stageTasks,
  "# Complete role prompt files",
  "",
  ...rolePrompts,
].join("\n")

await writeFile(resolve(REPO_ROOT, "SUBAGENT_PROMPTS.md"), `${body.trimEnd()}\n`, "utf8")
console.log(JSON.stringify({
  ok: true,
  path: "SUBAGENT_PROMPTS.md",
  agents: agentFiles.length,
  executablePipelineAgents: PIPELINE_AGENTS.length,
  stages: Object.keys(STAGE_PLANS).length,
}, null, 2))
